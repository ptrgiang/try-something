// Regenerates src/lib/badge-art.ts: the maker badges as finished SVG strings.
// Badges are embedded with <img>, which can't load web fonts, so every word is
// drawn as a path here. Run after changing the artwork: node scripts/build-badges.mjs
import { readFileSync, writeFileSync } from "node:fs";
import satori from "satori";

const font = (family, weight) => readFileSync(`node_modules/@fontsource/${family}/files/${family}-latin-${weight}-normal.woff`);
const fonts = [
  { name: "Fraunces", data: font("fraunces", 600), weight: 600, style: "normal" },
  { name: "Manrope", data: font("manrope", 800), weight: 800, style: "normal" },
];

// One line of text as path data, with its top-left corner at (x, top).
async function text(str, { x, top, family, size, spacing = 0, fill }) {
  const svg = await satori(
    { type: "div", props: { style: { display: "flex", fontFamily: family, fontWeight: family === "Fraunces" ? 600 : 800, fontSize: size, letterSpacing: spacing, lineHeight: 1 }, children: str } },
    { width: 400, height: Math.ceil(size * 1.3), fonts },
  );
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join("");
  return `<path transform="translate(${x} ${top})" fill="${fill}" d="${d}"/>`;
}

const mark = (x, y, size) =>
  `<g transform="translate(${x} ${y}) scale(${size / 32})"><rect width="32" height="32" rx="8" fill="#ff6a45"/><path d="M11.5 9.5v16.4l4.4-4.1 3.1 6.2 3-1.5-3.1-6.2h5.9z" fill="#17141f" stroke="#17141f" stroke-width="1.5" stroke-linejoin="round"/><path d="M8.2 7 6.2 5M11.5 5.6V3.4M14.8 7l2-2" fill="none" stroke="#fffdf9" stroke-width="2.4" stroke-linecap="round"/></g>`;

const svg = (w, h, label, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" role="img" aria-label="${label}"><title>${label}</title>${body}</svg>`;

async function pill(theme) {
  const dark = theme === "dark";
  const bg = dark ? "#fffdf9" : "#17141f";
  const ink = dark ? "#17141f" : "#fffdf9";
  const sub = dark ? "#6b6577" : "#b9b4c2";
  return svg(182, 44, "Listed on Try Something", [
    `<rect width="182" height="44" rx="22" fill="${bg}"/>`,
    mark(7, 6, 32),
    await text("LISTED ON", { x: 49, top: 11.5, family: "Manrope", size: 8.5, spacing: 0.9, fill: sub }),
    await text("Try Something", { x: 49, top: 20, family: "Fraunces", size: 16, fill: ink }),
  ].join(""));
}

async function verified(theme) {
  const dark = theme === "dark";
  const c = dark
    ? { bg: "#2a2240", stroke: "#9b85ff", seal: "#9b85ff", check: "#17141f", eyebrow: "#c9bcff", ink: "#fffdf9" }
    : { bg: "#efeaff", stroke: "#7a5cff", seal: "#7a5cff", check: "#fffdf9", eyebrow: "#5a3fe0", ink: "#17141f" };
  return svg(252, 52, "Verified maker on Try Something", [
    `<rect x="0.75" y="0.75" width="250.5" height="50.5" rx="25.25" fill="${c.bg}" stroke="${c.stroke}" stroke-width="1.5"/>`,
    `<circle cx="26" cy="26" r="17" fill="${c.seal}"/>`,
    `<path d="M18.5 26.5l5 5 9.5-10" fill="none" stroke="${c.check}" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"/>`,
    await text("VERIFIED MAKER", { x: 52, top: 14, family: "Manrope", size: 9, spacing: 1, fill: c.eyebrow }),
    await text("on Try Something", { x: 52, top: 25, family: "Fraunces", size: 16, fill: c.ink }),
    mark(214, 14, 24),
  ].join(""));
}

const art = {
  pill: { light: await pill("light"), dark: await pill("dark") },
  verified: { light: await verified("light"), dark: await verified("dark") },
};
const out = `// Generated by scripts/build-badges.mjs. Don't edit by hand.\nexport const BADGE_ART = ${JSON.stringify(art, null, 2)} as const;\n`;
writeFileSync("src/lib/badge-art.ts", out);
console.log(`badge-art.ts: ${(out.length / 1024).toFixed(1)} KB`);
